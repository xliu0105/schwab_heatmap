const STRINGS: Record<Lang, Record<Key, string>> = { zh, en }

export const LangContext = createContext<Lang>('zh')

export interface T {
  lang: Lang
  t(key: Key, vars?: Record<string, string | number>): string
  universe(id: UniverseId): string
  period(id: Period): string
  sector(name: string): string
  industry(name: string): string
  message(m: StatusInfo['message']): string | undefined
  cloudError(e: CloudState['error']): string | undefined
  time(t: number): string
}

export function translator(lang: Lang): T {
  const t = (key: Key, vars: Record<string, string | number> = {}) =>
    STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
  return {
    lang,
    t,
    universe: (id) => (isEtfUniverse(id) ? etfTicker(id) : UNIVERSES.find((u) => u.id === id)?.[lang] ?? id),
    period: (id) => PERIODS.find((p) => p.id === id)?.[lang] ?? id,
    sector: (name) => sectorName(name, lang),
    industry: (name) => industryName(name, lang),
    message: (m) => {
      if (!m) return undefined
      const base = t(`msg_${m.key}` as `msg_${MsgKey}`)
      return m.detail ? `${base}: ${m.detail}` : base
    },
    cloudError: (e) => {
      if (!e) return undefined
      const base = t(`cloudErr_${e.key}` as Key)
      return e.detail ? `${base}: ${e.detail}` : base
    },
    time: (ts) => new Date(ts).toLocaleTimeString(lang === 'zh' ? 'zh-CN' : 'en-US', { hour: '2-digit', minute: '2-digit' })
  }
}

export const useT = (): T => translator(useContext(LangContext))
