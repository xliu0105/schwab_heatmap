export function classifyNasdaq(nasdaqSector: string, nasdaqIndustry: string): { sector: string; industry: string; mapped: boolean } {
  const ind = nasdaqIndustry.trim()
  const hit = NASDAQ_INDUSTRY[`${ind}|${nasdaqSector.trim()}`] ?? NASDAQ_INDUSTRY[ind]
  if (hit) return { sector: hit[0], industry: hit[1], mapped: true }
  return { sector: NASDAQ_SECTOR[nasdaqSector.trim()] ?? OTHER, industry: OTHER, mapped: !ind }
}
